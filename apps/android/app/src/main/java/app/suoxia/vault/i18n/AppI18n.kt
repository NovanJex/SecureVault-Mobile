package app.suoxia.vault.i18n

import java.util.Locale

object AppI18n {
    fun isChinese(): Boolean {
        val lang = Locale.getDefault().language.lowercase(Locale.ROOT)
        return lang.startsWith("zh")
    }

    fun t(zh: String): String {
        if (isChinese()) return zh
        return enDict[zh] ?: zh
    }

    fun tf(zhTemplate: String, vararg args: Any): String {
        val template = t(zhTemplate)
        return try {
            String.format(Locale.getDefault(), template, *args)
        } catch (_: Exception) {
            template
        }
    }

